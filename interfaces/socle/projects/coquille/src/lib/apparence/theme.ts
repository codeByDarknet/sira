/**
 * La page d'entrée porte un nonce neuf à chaque requête (`ngCspNonce`, posé par nginx). PrimeNG
 * le recopie sur ses balises <style>, seules autorisées par la politique de contenu.
 * Hors nginx (serveur de développement), le gabarit reste tel quel et aucun nonce n'est passé.
 */
export function lireNonce(): string | undefined {
  const nonce = globalThis.document?.querySelector('[ngCspNonce]')?.getAttribute('ngCspNonce');
  return nonce && !nonce.startsWith('__') ? nonce : undefined;
}

export function fournirApparence(): EnvironmentProviders {
  return providePrimeNG({
    ripple: false,
    translation: TRADUCTION_FR,
    csp: { nonce: lireNonce() },
    theme: {
      preset: THEME_SIRA,
      options: {
        darkModeSelector: false,
        // Ordre déclaré aussi en tête de styles/tailwind.css : les utilitaires passent après PrimeNG.
        cssLayer: { name: 'primeng', order: 'theme, base, primeng' },
      },
    },
  });
}
